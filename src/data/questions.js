export const saboteurKeys = [
  'insistente',
  'prestativo',
  'hiper_realizador',
  'vitima',
  'hiper_racional',
  'hipervigilante',
  'inquieto',
  'controlador',
  'esquivo',
]

export const juizKeys = ['juiz_auto', 'juiz_outros', 'juiz_circ']

export function calcScores(answers) {
  const scores = {}
  const allKeys = [...saboteurKeys, ...juizKeys]
  allKeys.forEach(k => { scores[k] = 0 })

  blocks.forEach(block => {
    block.questions.forEach(q => {
      const val = answers[q.id] ?? 0
      const score = q.reverse ? 6 - val : val
      scores[q.saboteur] = (scores[q.saboteur] || 0) + score
    })
  })

  return scores
}

export function getMaxScore(key) {
  let count = 0
  blocks.forEach(b => b.questions.forEach(q => { if (q.saboteur === key) count++ }))
  return count * 5
}

export function getRelativeScore(key, scores) {
  const count = getMaxScore(key) / 5
  if (!count) return 0
  return Math.round(((scores[key] || 0) / count) * 20) / 10
}

export function getScorePercentage(key, scores) {
  const max = getMaxScore(key)
  if (!max) return 0
  return Math.round(((scores[key] || 0) / max) * 100)
}

export function getTopSaboteurs(scores) {
  return saboteurKeys
    .map(k => ({ key: k, score: getRelativeScore(k, scores) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 2)
    .map(s => s.key)
}
